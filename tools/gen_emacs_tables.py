#!/usr/bin/env python3
"""Regenerate src/dialects/emacs_tables.zig from the local Emacs: word/whitespace syntax
ranges and the case canonicalization table, as seen by the host (emacs -Q --batch,
*scratch* buffer). Usage: tools/gen_emacs_tables.py [/path/to/emacs]"""
import os, subprocess, sys, tempfile
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
emacs = sys.argv[1] if len(sys.argv) > 1 else "/opt/homebrew/bin/emacs"
el = r''';;; -*- lexical-binding: t -*-
(defun irx-runs (cls)
  (let ((c 0) (start nil))
    (while (<= c #x10FFFF)
      (let ((p (eq (char-syntax c) cls)))
        (cond ((and p (not start)) (setq start c))
              ((and (not p) start) (princ (format "%c %d %d\n" cls start (1- c))) (setq start nil))))
      (setq c (1+ c)))
    (when start (princ (format "%c %d %d\n" cls start #x10FFFF)))))
(princ (format "version %s\n" emacs-version))
(irx-runs ?w)
(irx-runs ?\s)
(let ((c 0) (start 0) (cur (aref char-script-table 0)))
  (while (<= c #x10FFFF)
    (let ((s (aref char-script-table c)))
      (unless (eq s cur) (princ (format "s %d %d %s\n" start (1- c) cur)) (setq start c cur s)))
    (setq c (1+ c)))
  (princ (format "s %d %d %s\n" start #x10FFFF cur)))
(let ((canon (char-table-extra-slot (current-case-table) 1)) (c 0))
  (while (<= c #x10FFFF) (let ((d (aref canon c))) (when (and d (/= d c)) (princ (format "c %d %d\n" c d)))) (setq c (1+ c))))
'''
with tempfile.NamedTemporaryFile("w", suffix=".el", delete=False) as f:
    f.write(el)
out = subprocess.run([emacs, "-Q", "--batch", "-l", f.name], capture_output=True, text=True, check=True).stdout
os.unlink(f.name)
word, space, canon, scripts, version = [], [], [], [], "?"
for line in out.splitlines():
    k, *v = line.split(" ")
    if k == "version": version = v[0]
    elif k == "w": word.append((int(v[0]), int(v[1])))
    elif k == "" and len(v) == 3: space.append((int(v[1]), int(v[2])))  # "  a b": class char is a space
    elif k == "c": canon.append((int(v[0]), int(v[1])))
    elif k == "s": scripts.append((int(v[0]), int(v[1]), v[2]))
names = sorted({s for _, _, s in scripts})
fmt = lambda xs: "\n".join(f"    .{{ 0x{a:X}, 0x{b:X} }}," for a, b in xs)
open(os.path.join(root, "src/dialects/emacs_tables.zig"), "w").write(f"""//! Generated by tools/gen_emacs_tables.py from Emacs {version} (-Q --batch, *scratch*). Do not edit.
pub const word = [_][2]u21{{
{fmt(word)}
}};
pub const space = [_][2]u21{{
{fmt(space)}
}};
/// char-script-table runs: {{first, last, script id}}; ids index script_names (nil = no script).
pub const script_names = [_][]const u8{{ {", ".join('"%s"' % n for n in names)} }};
pub const scripts = [_][3]u21{{
{chr(10).join(f"    .{{ 0x{a:X}, 0x{b:X}, {names.index(s)} }}," for a, b, s in scripts)}
}};
/// Case canonicalization (case-fold-search translate table), sorted by source.
pub const canon = [_][2]u21{{
{fmt(canon)}
}};
""")
print(f"emacs {version}: {len(word)} word ranges, {len(space)} space ranges, {len(canon)} canon pairs, {len(scripts)} script runs")
